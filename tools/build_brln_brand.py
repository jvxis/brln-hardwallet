"""Compile the official BRLN PNG into opaque RGB565 firmware assets."""
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
source=Image.open(root/'assets/brand/brln-logo.png').convert('RGBA')
lines=['// Generated by tools/build_brln_brand.py from the official br-ln.com logo.', '#pragma once', '#include <stdint.h>', '#include <pgmspace.h>', 'const uint16_t BRLN_BACKGROUND = 0x0883;']
for name,width,height in [('BOOT',224,94),('MARK',48,20)]:
 image=source.resize((width,height),Image.Resampling.LANCZOS)
 bg=Image.new('RGBA',image.size,(8,17,31,255));bg.alpha_composite(image)
 values=[((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b,a in bg.getdata()]
 lines += [f'const uint16_t BRLN_{name}_WIDTH = {width};',f'const uint16_t BRLN_{name}_HEIGHT = {height};',f'const uint16_t BRLN_{name}_PIXELS[] PROGMEM = {{']
 lines += [','.join(f'0x{n:04x}' for n in values[i:i+16])+',' for i in range(0,len(values),16)]
 lines += ['};']
(root/'wallet/brln_brand.h').write_text('\n'.join(lines)+'\n',encoding='utf-8')
