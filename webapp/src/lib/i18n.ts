const staleSuffix = ' A última consulta continua visível; os dados podem estar desatualizados.'

export function translate(text: string, language: Lang, vars: Record<string, string | number> = {}): string {
  let out = text
  if (language === 'en') {
    if (en[text] !== undefined) out = en[text]
    else if (text.endsWith(staleSuffix)) out = translate(text.slice(0, -staleSuffix.length), language) + ' The last query stays visible; data may be out of date.'
    else for (const [pattern, render] of patterns) { const m = text.match(pattern); if (m) { out = render(m); break } }
  } else if (pt[text] !== undefined) out = pt[text]
  return out.replace(/\{(\w+)\}/g, (whole, key) => vars[key] === undefined ? whole : String(vars[key]))
}

